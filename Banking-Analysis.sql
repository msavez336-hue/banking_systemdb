CREATE DATABASE BANKING_SYSTEMDB;

USE BANKING_SYSTEMDB;

CREATE TABLE CUSTOMERS (
CUSTOMERID INT PRIMARY KEY,
FIRSTNAME VARCHAR(50),
LASTNAME VARCHAR(50),
EMAIL VARCHAR(100),
PHONE VARCHAR(15)
);

ALTER TABLE CUSTOMERS
